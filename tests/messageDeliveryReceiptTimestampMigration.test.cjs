const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const sql = fs.readFileSync(path.join(__dirname, '../supabase/migrations/0047_server_generated_delivery_receipt_timestamps.sql'), 'utf8');

test('delivery receipt timestamps are generated by the database, not trusted from clients', () => {
  assert.match(sql, /new\.delivered_at\s*:=\s*pg_catalog\.now\(\)/i);
  assert.match(sql, /before insert on public\.message_delivery_receipts/i);
  assert.match(sql, /execute function private\.enforce_message_delivery_receipt_timestamp\(\)/i);
});

test('receipt timestamp trigger function is not directly executable by client roles', () => {
  assert.match(sql, /revoke all on function private\.enforce_message_delivery_receipt_timestamp\(\) from public, anon, authenticated/i);
  assert.match(sql, /set search_path = ''/i);
});
